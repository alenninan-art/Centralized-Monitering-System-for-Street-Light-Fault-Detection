export const GENERATE_HISTORICAL_TELEMETRY = (): TelemetryPoint[] => {
  const times = [
    '00:00', '02:00', '04:00', '06:00', '08:00', '10:00',
    '12:00', '14:00', '16:00', '18:00', '20:00', '22:00', '23:59'
  ];

  return times.map((t, idx) => {
    const isNight = idx <= 3 || idx >= 9;
    const baseVoltage = 228 + Math.floor(Math.sin(idx) * 4);

    return {
      timestamp: t,
      timeLabel: t,
      voltage: baseVoltage,
      current: isNight ? Number((0.41 + Math.random() * 0.03).toFixed(2)) : 0.02,
      power: isNight ? Number((94 + Math.random() * 5).toFixed(1)) : 4.2,
      lightIntensity: isNight ? Math.floor(82 + Math.random() * 12) : 5,
      temperature: Math.floor(27 + Math.sin(idx / 2) * 8),
    };
  });
};

